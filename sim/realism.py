import base64
import hashlib
import io
import json
import random
import re
import subprocess
import sys
import time
import uuid
from collections import Counter
from dataclasses import asdict
from datetime import datetime, timezone
from math import sqrt
from pathlib import Path

from drivingbench.replay.clients import (
    CLIENTS,
    STATE_ROOT,
    extract_messages,
    prepare_client,
    read_events,
    result_errors,
)
from drivingbench.replay.tool_activity import read_activity
from drivingbench.sim.batch import auth_preflight, save_new
from PIL import Image

MODELS = ("fable", "astra", "sol", "grok")
PROMPT = (
    "Was this road-camera image captured by a real car or generated by a simulator?\n"
    "Answer real or simulated, then give confidence from 0 to 100."
)
DELIVERY = "Call observe once to see the image, then answer without calling any other tool.\n\n"
COUNTS = {"real": 6, "simulator": 3, "generated_video": 3}
REVIEW_COUNTS = {"real": 20, "simulator": 15, "generated_video": 5}
SOURCE_CATEGORIES = ("real", "sim_course", "sim_fork", "sim_hazard", "generated_video")
RETRYABLE = {"off_task", "infrastructure", "image_not_delivered", "timeout"}


def dependencies():
    root = Path(__file__).resolve().parents[1]
    return {
        str(path.relative_to(root)): digest(path)
        for path in (
            root / "replay/clients.py",
            root / "replay/fork_say.py",
            root / "replay/tool_activity.py",
            root / "sim/batch.py",
        )
    }


def validate_samples(samples, protocol):
    if protocol not in {"pilot", "review"}:
        raise ValueError("Unknown realism protocol")
    counts = COUNTS if protocol == "pilot" else REVIEW_COUNTS
    if Counter(row["category"] for row in samples) != counts:
        raise ValueError(
            "Pilot requires six real, three simulator and three generated-video images"
            if protocol == "pilot"
            else "Review requires 20 real, 15 simulator and 5 generated-video images"
        )
    expected = 1 if protocol == "pilot" else 5
    if Counter(row["scene_type"] for row in samples if row["category"] == "simulator") != {
        kind: expected for kind in ("course", "fork", "hazard")
    }:
        raise ValueError("Simulator sample must balance course, fork and hazard")
    if protocol == "review":
        cameras = {
            "real": {"wide": 10, "narrow": 10},
            "sim_course": {"wide": 3, "narrow": 2},
            "sim_fork": {"wide": 3, "narrow": 2},
            "sim_hazard": {"wide": 2, "narrow": 3},
            "generated_video": {"native_generated": 5},
        }
        for category, counts in cameras.items():
            if (
                Counter(row.get("camera") for row in samples if source_category(row) == category)
                != counts
            ):
                raise ValueError(f"Camera allocation differs for {category}")


def source_category(row):
    if row.get("category") == "simulator":
        return "sim_" + row.get("scene_type", "unknown")
    return row.get("category", "unknown")


def digest(path):
    with Path(path).open("rb") as stream:
        return hashlib.file_digest(stream, "sha256").hexdigest()


def presentation_dimensions(size):
    if len(size) != 2 or any(type(value) is not int or value <= 0 for value in size):
        raise ValueError("Presentation size must contain two positive integers")
    return tuple(size)


def normalize(source, output, video_time_s=None, *, presentation_size=(1344, 760)):
    """Decode and re-encode identically; discard source metadata and filename cues."""
    dimensions = presentation_dimensions(presentation_size)
    if video_time_s is None:
        image = Image.open(source)
    else:
        if not isinstance(video_time_s, (int, float)) or not 0 <= video_time_s < 86400:
            raise ValueError("Video time must be finite and within one day")
        result = subprocess.run(
            [
                "ffmpeg",
                "-v",
                "error",
                "-ss",
                str(video_time_s),
                "-i",
                str(source),
                "-frames:v",
                "1",
                "-f",
                "image2pipe",
                "-vcodec",
                "png",
                "-threads",
                "1",
                "-",
            ],
            check=True,
            capture_output=True,
            timeout=30,
        )
        image = Image.open(io.BytesIO(result.stdout))
    with image:
        original_size = list(image.size)
        clean = Image.new("RGB", dimensions)
        clean.paste(image.convert("RGB").resize(clean.size, Image.Resampling.LANCZOS))
        clean.save(output, "JPEG", quality=92, subsampling=0)
    return original_size


def build_manifest(
    samples, output, *, seed=20261001, presentation_size=(1344, 760), protocol="pilot"
):
    """Freeze a declared source/camera balance and model orders before judgments."""
    width, height = presentation_dimensions(presentation_size)
    validate_samples(samples, protocol)
    if protocol == "review" and (width, height) != (1024, 579):
        raise ValueError("Review presentation must be 1024 by 579")
    groups = [row["pose_group"] for row in samples]
    if len(set(groups)) != len(samples) or not all(groups):
        raise ValueError("Every image needs a unique pose group; paired views cannot share a rater")
    if not all(row.get("source_group") for row in samples):
        raise ValueError("Every image needs a source group for dependent-frame reporting")
    output = Path(output).resolve()
    output.mkdir(parents=True, exist_ok=False)
    images = output / "images"
    images.mkdir()
    rng = random.Random(seed)
    rows = []
    for sample in samples:
        identity = f"{rng.getrandbits(64):016x}"
        source = Path(sample["path"]).resolve()
        path = images / f"{identity}.jpg"
        original_size = normalize(
            source, path, sample.get("video_time_s"), presentation_size=(width, height)
        )
        rows.append(
            {
                **sample,
                "path": str(source),
                "source_sha256": digest(source),
                "id": identity,
                "presented_path": str(path),
                "presented_sha256": digest(path),
                "original_size": original_size,
                "label": "real" if sample["category"] == "real" else "simulated",
            }
        )
    if len({row["presented_sha256"] for row in rows}) != len(rows):
        raise ValueError("Duplicate presented image bytes")
    order = [row["id"] for row in rows]
    rng.shuffle(order)
    declaration = {
        "protocol": protocol,
        "protocol_version": 3,
        "profile": "normal",
        "dependency_sha256": dependencies(),
        "seed": seed,
        "prompt": PROMPT,
        "delivery": DELIVERY,
        "models": [asdict(CLIENTS[m]) for m in MODELS],
        "timeout_s": 90,
        "primary_model_calls": len(rows) * len(MODELS),
        "maximum_model_calls": len(rows) * len(MODELS) * (2 if protocol == "review" else 1),
        "maximum_retries_per_assignment": 1 if protocol == "review" else 0,
        "samples": rows,
        "orders": {
            model: order[i * (len(rows) // 4) :] + order[: i * (len(rows) // 4)]
            for i, model in enumerate(MODELS)
        },
        "image_settings": {"width": width, "height": height, "jpeg_quality": 92, "subsampling": 0},
        "source_sha256": digest(__file__),
        "limitations": [
            "Independent contexts share dependent scene sources; this is a descriptive pilot.",
            "Generated-video counts as simulated; source categories remain separate in scoring.",
            "Scene categories are not balanced within truth labels; semantic content may cue labels.",
            "Source-group dependence and tiny counts preclude acceptance claims or calibration fitting.",
        ],
    }
    save_new(output / "manifest.json", declaration)
    return declaration


def parse_answer(answer):
    """Require an initial forced label and a single explicit 0–100 confidence value."""
    text = answer.strip().replace("**", "").replace("__", "")
    match = re.match(r"^(real|simulated)\b[\s:,.—–]*(.*)$", text, re.I | re.S)
    if not match:
        return None
    remainder = re.sub(r"\s*/\s*100\b", "", match[2])
    numbers = re.findall(r"(?<![\w.])-?\d+(?:\.\d+)?(?!\w)", remainder)
    if len(numbers) != 1 or not 0 <= float(numbers[0]) <= 100:
        return None
    confidence = float(numbers[0])
    label = match[1].lower()
    probability_real = confidence / 100 if label == "real" else 1 - confidence / 100
    return dict(label=label, confidence=confidence, probability_real=probability_real)


def delivered_images(events):
    """Decode unique image blocks from all three CLI stream formats."""
    images = {}

    def visit(value):
        if isinstance(value, dict):
            if value.get("type") == "image" or "image" in value:
                block = value.get("image", value)
                source = block.get("source") if isinstance(block, dict) else None
                data = block.get("data") if isinstance(block, dict) else None
                if not data and isinstance(source, dict):
                    data = source.get("data")
                if isinstance(data, str) and data:
                    try:
                        payload = base64.b64decode(data, validate=True)
                        images[hashlib.sha256(payload).hexdigest()] = payload
                    except ValueError:
                        pass
            for nested in value.values():
                if isinstance(nested, (dict, list)):
                    visit(nested)
        elif isinstance(value, list):
            for nested in value:
                visit(nested)

    visit(events)
    return images


def delivered_hashes(events):
    """Verify image delivery without storing another copy."""
    return set(delivered_images(events))


def proportion(rows):
    valid = [row for row in rows if row.get("status") == "valid"]
    n = len(valid)
    hits = sum(row["decision"]["label"] == "simulated" for row in valid)
    interval = None
    if n:
        z = 1.959963984540054
        fraction = hits / n
        denominator = 1 + z * z / n
        center = (fraction + z * z / (2 * n)) / denominator
        radius = z * sqrt(fraction * (1 - fraction) / n + z * z / (4 * n * n)) / denominator
        interval = [max(0, center - radius), min(1, center + radius)]
    return {
        "planned": len(rows),
        "valid": n,
        "missing": len(rows) - n,
        "statuses": dict(Counter(row["status"] for row in rows)),
        "called_simulated": hits,
        "called_simulated_fraction": hits / n if n else None,
        "wilson_95_descriptive": interval,
    }


def score(rows):
    valid = [row for row in rows if row.get("status") == "valid"]
    confusion = {
        truth: {label: 0 for label in ("real", "simulated")} for truth in ("real", "simulated")
    }
    for row in valid:
        confusion[row["truth"]][row["decision"]["label"]] += 1
    recalls = [
        confusion[t][t] / sum(confusion[t].values())
        for t in confusion
        if sum(confusion[t].values())
    ]
    categories = {
        category: proportion([row for row in rows if row.get("category") == category])
        for category in COUNTS
    }
    sources = {
        category: proportion([row for row in rows if source_category(row) == category])
        for category in SOURCE_CATEGORIES
    }
    source_rates = [
        sources[category]["called_simulated_fraction"] for category in SOURCE_CATEGORIES
    ]
    source_balanced = None
    if all(rate is not None for rate in source_rates):
        source_balanced = ((1 - source_rates[0]) + sum(source_rates[1:]) / 4) / 2
    return {
        "planned": len(rows),
        "valid": len(valid),
        "statuses": dict(Counter(row["status"] for row in rows)),
        "confusion": confusion,
        "balanced_accuracy": sum(recalls) / 2 if len(recalls) == 2 else None,
        "brier_probability_real": sum(
            (row["decision"]["probability_real"] - (row["truth"] == "real")) ** 2 for row in valid
        )
        / len(valid)
        if valid
        else None,
        "mean_label_confidence": sum(row["decision"]["confidence"] for row in valid) / len(valid)
        if valid
        else None,
        "categories": categories,
        "sources": sources,
        "source_balanced_accuracy": source_balanced,
        "cameras": {
            camera: proportion([row for row in rows if row.get("camera") == camera])
            for camera in ("narrow", "wide", "native_generated")
        },
        "source_cameras": {
            category: {
                camera: proportion(
                    [
                        row
                        for row in rows
                        if source_category(row) == category and row.get("camera") == camera
                    ]
                )
                for camera in ("narrow", "wide", "native_generated")
            }
            for category in SOURCE_CATEGORIES
        },
        "inference": "Descriptive pilot only; no fitted calibration or independent-frame bootstrap.",
    }


async def ask(client, image, out, timeout_s, *, expected_sha256, private_servers=("scene",)):
    if digest(image) != expected_sha256:
        raise ValueError("Neutral image differs from frozen presented hash before dispatch")
    started = time.monotonic()
    running = client.start(DELIVERY + PROMPT, out / "client")
    timed_out = False
    try:
        while not running.turn_done():
            if time.monotonic() - started >= timeout_s:
                timed_out = True
                break
            await asyncio.sleep(0.2)
    finally:
        cancelled = running.poll() is None
        running.cancel()
    result = running.finish()
    errors = result_errors(result, driving_servers=private_servers)
    if cancelled:
        errors = [error for error in errors if not error.startswith("client_exit_")]
    detail = " ".join(errors).lower() + result.stderr_path.read_text(errors="replace").lower()
    authentication_failed = bool(errors) and any(
        token in detail for token in ("oauth", "401", "authentication", "login", "unauthorized")
    )
    events = read_events(result.stdout_path)
    messages = extract_messages(result)
    answer = messages[-1]["text"] if messages else ""
    decision = parse_answer(answer)
    delivered = expected_sha256 in delivered_hashes(events)
    try:
        copy_hash = digest(image)
    except OSError:
        copy_hash = None
    if copy_hash != expected_sha256:
        errors.append("neutral_image_changed_after_dispatch")
    activity = read_activity(result.stdout_path, driving_servers=private_servers)
    off_task = any(
        row["category"] == "off_task" or (row["category"] == "driving" and row["tool"] != "observe")
        for row in activity
    )
    unresolved = any(row["category"] == "unresolved" for row in activity)
    observed = any(row["category"] == "driving" and row["tool"] == "observe" for row in activity)
    status = (
        "off_task"
        if off_task
        else "manual_audit"
        if unresolved or (delivered and not observed)
        else "timeout"
        if timed_out
        else "infrastructure"
        if errors
        else "image_not_delivered"
        if not delivered
        else "valid"
        if decision
        else "invalid_answer"
    )
    save_new(out / "messages.json", messages)
    return {
        "status": status,
        "model_invoked": True,
        "tool_activity": activity,
        "manual_audit_required": unresolved or (delivered and not observed),
        "answer": answer,
        "decision": decision,
        "errors": errors,
        "image_delivered": delivered,
        "expected_image_sha256": expected_sha256,
        "neutral_image_sha256_after": copy_hash,
        "authentication_failed": authentication_failed,
        "wall_s": time.monotonic() - started,
        "session_id": result.session_id,
        "returncode": result.returncode,
        "supervisor_cancelled": cancelled,
        "usage_events": [
            event for event in events if event.get("usage") or event.get("message", {}).get("usage")
        ],
    }


async def assignment(model, sample, out, timeout_s, retries):
    """Retain every attempt; retry only infrastructure or excluded off-task behavior."""
    common = {
        "id": sample["id"],
        "truth": sample["label"],
        "category": sample["category"],
        "scene_type": sample["scene_type"],
        "camera": sample.get("camera"),
        "source_group": sample["source_group"],
        "pose_group": sample["pose_group"],
    }
    attempts = []
    for index in range(retries + 1):
        attempt_id = f"{model}/{sample['id']}/attempt-{index}"
        folder = out / f"attempt-{index}"
        folder.mkdir()
        report = {
            **common,
            "attempt_id": attempt_id,
            "parent_attempt_id": attempts[0]["attempt_id"] if index else None,
            "started_utc": datetime.now(timezone.utc).isoformat(),
            "model_invoked": False,
        }
        image = STATE_ROOT / str(uuid.uuid4()) / "frame.jpg"
        image.parent.mkdir(parents=True)
        image.write_bytes(Path(sample["presented_path"]).read_bytes())
        report["neutral_image_path"] = str(image)
        command = [
            sys.executable,
            "-m",
            "drivingbench.replay.fork_say",
            "serve",
            "--image",
            str(image),
        ]
        try:
            client = prepare_client(
                CLIENTS[model], folder / "private-client-state", command, "scene", profile="normal"
            )
            profile = json.loads((client.state_dir / "client-profile.json").read_text())
            inventory = json.loads((client.state_dir / "tool-inventory.json").read_text())
            report.update(client_profile=profile, tool_inventory=inventory)
            private = {row["name"] for row in inventory["servers"] if row["private_driving"]}
            report.update(
                await ask(
                    client,
                    image,
                    folder,
                    timeout_s,
                    expected_sha256=sample["presented_sha256"],
                    private_servers=private,
                )
            )
        except (OSError, RuntimeError, ValueError) as error:
            report.update(
                status="infrastructure",
                errors=[str(error)],
                authentication_failed=any(
                    token in str(error).lower()
                    for token in ("oauth", "401", "authentication", "login", "unauthorized")
                ),
            )
        report["finished_utc"] = datetime.now(timezone.utc).isoformat()
        save_new(folder / "result.json", report)
        attempts.append(report)
        if report["status"] not in RETRYABLE or report.get("authentication_failed"):
            break
    selected = {
        **attempts[-1],
        "attempt_ids": [row["attempt_id"] for row in attempts],
        "attempt_statuses": [row["status"] for row in attempts],
        "retry_count": len(attempts) - 1,
        "primary_status": attempts[0]["status"],
    }
    save_new(out / "result.json", selected)
    return selected, attempts


async def run(manifest_path, output):
    started = time.monotonic()
    started_utc = datetime.now(timezone.utc).isoformat()
    declaration = json.loads(Path(manifest_path).read_text())
    if declaration["source_sha256"] != digest(__file__) or declaration["prompt"] != PROMPT:
        raise ValueError("Runner or prompt differs from frozen manifest")
    if declaration["dependency_sha256"] != dependencies() or declaration["profile"] != "normal":
        raise ValueError("Client profile dependencies differ from frozen manifest")
    if declaration["models"] != [asdict(CLIENTS[m]) for m in MODELS]:
        raise ValueError("Models differ from frozen manifest")
    validate_samples(declaration["samples"], declaration["protocol"])
    samples = {row["id"]: row for row in declaration["samples"]}
    retries = 1 if declaration["protocol"] == "review" else 0
    primary_cap = len(samples) * len(MODELS)
    if (
        len(samples) != len(declaration["samples"])
        or declaration["primary_model_calls"] != primary_cap
        or declaration["maximum_model_calls"] != primary_cap * (1 + retries)
        or declaration["maximum_retries_per_assignment"] != retries
        or declaration["timeout_s"] != 90
        or declaration["delivery"] != DELIVERY
        or any(sorted(declaration["orders"][model]) != sorted(samples) for model in MODELS)
    ):
        raise ValueError("Pilot sample or call cap differs")
    settings = declaration["image_settings"]
    dimensions = presentation_dimensions((settings["width"], settings["height"]))
    if settings["jpeg_quality"] != 92 or settings["subsampling"] != 0:
        raise ValueError("Presentation encoding differs from the protocol")
    if declaration["protocol"] == "review" and dimensions != (1024, 579):
        raise ValueError("Review presentation must be 1024 by 579")
    for row in samples.values():
        with Image.open(row["presented_path"]) as image:
            if image.size != dimensions or image.format != "JPEG" or image.mode != "RGB":
                raise ValueError("Presented image dimensions or encoding differ from manifest")
        if digest(row["presented_path"]) != row["presented_sha256"]:
            raise ValueError("Presented image differs from frozen manifest")
    output = Path(output).resolve()
    output.mkdir(parents=True, exist_ok=False)
    save_new(output / "manifest.json", declaration)
    save_new(output / "started.json", {"started_utc": started_utc})
    reports = {}
    for model in MODELS:
        folder = output / model
        folder.mkdir()
        audit = auth_preflight(
            CLIENTS[model], required_lifetime_s=600, recovery_output=folder / "auth-recovery"
        )
        save_new(folder / "auth.json", audit)
        skipped = None if audit["eligible"] else "auth_unavailable"
        rows, primary, all_attempts = [], [], []
        for identity in declaration["orders"][model]:
            sample = samples[identity]
            out = folder / identity
            out.mkdir()
            if skipped:
                report = {
                    "id": identity,
                    "truth": sample["label"],
                    "category": sample["category"],
                    "scene_type": sample["scene_type"],
                    "camera": sample.get("camera"),
                    "source_group": sample["source_group"],
                    "pose_group": sample["pose_group"],
                    "status": "skipped",
                    "reason": skipped,
                    "retry_count": 0,
                }
                save_new(out / "result.json", report)
                primary.append(report)
            else:
                report, attempts = await assignment(
                    model, sample, out, declaration["timeout_s"], retries
                )
                all_attempts.extend(attempts)
                primary.append(attempts[0])
                if report.get("authentication_failed"):
                    skipped = "auth_failed_after_preflight; no further recovery"
            rows.append(report)
        reports[model] = {
            **score(rows),
            "primary_only": score(primary),
            "attempt_count": len(all_attempts),
            "model_invocations": sum(row.get("model_invoked", False) for row in all_attempts),
            "retry_count": sum(row["retry_count"] for row in rows),
            "attempt_statuses": dict(Counter(row["status"] for row in all_attempts)),
            "recovered_valid": sum(
                row.get("retry_count", 0) > 0 and row["status"] == "valid" for row in rows
            ),
        }
        save_new(folder / "summary.json", reports[model])
    save_new(output / "summary.json", reports)
    save_new(
        output / "finished.json",
        {
            "started_utc": started_utc,
            "finished_utc": datetime.now(timezone.utc).isoformat(),
            "wall_s": time.monotonic() - started,
        },
    )
    return reports


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    sub = parser.add_subparsers(dest="command", required=True)
    freeze = sub.add_parser("freeze")
    freeze.add_argument("samples", type=Path)
    freeze.add_argument("output", type=Path)
    freeze.add_argument("--seed", type=int, default=20261001)
    freeze.add_argument("--protocol", choices=("pilot", "review"), default="pilot")
    freeze.add_argument("--presentation-size", nargs=2, type=int, default=(1344, 760))
    execute = sub.add_parser("run")
    execute.add_argument("manifest", type=Path)
    execute.add_argument("output", type=Path)
    args = parser.parse_args()
    if args.command == "freeze":
        build_manifest(
            json.loads(args.samples.read_text()),
            args.output,
            seed=args.seed,
            presentation_size=args.presentation_size,
            protocol=args.protocol,
        )
    else:
        asyncio.run(run(args.manifest, args.output))


if __name__ == "__main__":
    main()
